var update = flag.Bool("update", false, "rewrite the golden tree from the current output")

// fixture loads the deployment every test in this file renders, and refuses to
// hand it back if the toolkit would not accept it.
//
// This is not belt and braces. Build does not validate, so for six tasks the
// fixture declared two apps under cluster placement that
// cluster-placement-without-a-cluster refuses outright, and the golden tree
// grew routing for a shape `paisans apply` would never have produced. A golden
// file is only a specification of what an operator receives if the input is
// something an operator could have written, so the check belongs here, ahead of
// every test, rather than in one test somebody might not run.
func fixture(t *testing.T) *config.Config {
	t.Helper()
	cfg, err := config.Load(filepath.Join("testdata", "deployment.yaml"))
	if err != nil {
		t.Fatalf("loading the fixture configuration: %v", err)
	}
	if refusals := validate.Check(cfg).Refusals(); len(refusals) > 0 {
		for _, f := range refusals {
			t.Errorf("the fixture is a configuration the toolkit refuses:\n%s", f)
		}
		t.FailNow()
	}
	return cfg
}

func build(t *testing.T) *render.Plan {
	t.Helper()
	cfg := fixture(t)
	secrets, err := config.LoadSecrets(filepath.Join("testdata", "secrets.fixture.yaml"))
	if err != nil {
		t.Fatalf("loading the fixture secrets: %v", err)
	}
	plan, err := render.Build(cfg, secrets)
	if err != nil {
		t.Fatalf("building the plan: %v", err)
	}
	return plan
}

// The golden tree is the specification of what an operator receives. A diff
// here is a change in what lands on a host, so it is reviewed rather than
// regenerated by reflex.
func TestGoldenTree(t *testing.T) {
	plan := build(t)
	golden := filepath.Join("testdata", "golden")

	if *update {
		if err := os.RemoveAll(golden); err != nil {
			t.Fatal(err)
		}
		if err := render.Write(plan, golden); err != nil {
			t.Fatal(err)
		}
		t.Log("golden tree rewritten")
		return
	}

	dir := t.TempDir()
	if err := render.Write(plan, dir); err != nil {
		t.Fatal(err)
	}
	compareTrees(t, golden, dir)
}

// Determinism is not a nicety: rendering twice must produce byte identical
// output, or a diff between two renders says nothing about what changed.
func TestRenderIsDeterministic(t *testing.T) {
	first, second := t.TempDir(), t.TempDir()
	if err := render.Write(build(t), first); err != nil {
		t.Fatal(err)
	}
	if err := render.Write(build(t), second); err != nil {
		t.Fatal(err)
	}
	compareTrees(t, first, second)
}

// A clustered app connects to the local proxy and has no Postgres of its own.
// A pinned app is pinned all the way down: its own database, at its own site.
func TestPlacementShapesTheStack(t *testing.T) {
	files := map[string]string{}
	for _, f := range build(t).Files {
		files[f.Path] = f.Content
	}

	clustered, ok := files["home-a/srv/paisans/f2a9/talk/compose.yaml"]
	if !ok {
		t.Fatal("the clustered app was not rendered onto an apps site")
	}
	if strings.Contains(clustered, "postgres:") {
		t.Error("a clustered app was given a Postgres service of its own")
	}
	// Each instance connects to the HAProxy on its own site, at that site's
	// mesh address. Not 127.0.0.1: inside the app's bridge networked
	// container, loopback is the container itself.
	for site, address := range map[string]string{"home-a": "10.44.0.1", "home-b": "10.44.0.2"} {
		env := files[site+"/srv/paisans/f2a9/talk/.env"]
		if !strings.Contains(env, "@"+address+":5000/") {
			t.Errorf("the clustered app on %s does not connect to its own site's proxy at %s:\n%s", site, address, env)
		}
		if strings.Contains(env, "127.0.0.1") {
			t.Errorf("the clustered app on %s names a loopback address, which inside its container is the container itself:\n%s", site, env)
		}
		proxy := files[site+"/srv/paisans/f2a9/infra/haproxy/haproxy.cfg"]
		if !strings.Contains(proxy, "bind "+address+":5000") {
			t.Errorf("the HAProxy on %s does not listen on the mesh address its apps are given:\n%s", site, proxy)
		}
	}

	pinned, ok := files["vm/srv/paisans/f2a9/chat/compose.yaml"]
	if !ok {
		t.Fatal("the pinned app was not rendered at its site")
	}
	if !strings.Contains(pinned, "postgres:") {
		t.Error("a pinned app was not given its own Postgres")
	}
	if _, ok := files["home-a/srv/paisans/f2a9/chat/compose.yaml"]; ok {
		t.Error("a pinned app was rendered somewhere other than its site")
	}
	if !strings.Contains(pinned, "/srv/paisans/f2a9/chat/postgres:/var/lib/postgresql/data") {
		t.Error("a pinned stack does not use bind mounts under /srv")
	}
}

// Every published port binds the mesh address of the site it is rendered for
// and nothing else. Docker's own iptables rules bypass a host firewall such as
// ufw, so "8080:8080" on a host with a public address is reachable from the
// internet whatever the firewall says, and with no gate in front of it. The
// gateway reaches every app over the mesh, so the mesh is the only interface
// a port needs.
func TestPublishedPortsBindTheMeshAddress(t *testing.T) {
	cfg := fixture(t)
	published := publishedPorts(build(t))
	for _, p := range published {
		address := cfg.Sites[p.site].Address
		if !strings.HasPrefix(p.mapping, address+":") || strings.Count(p.mapping, ":") != 2 {
			t.Errorf("%s publishes %q, which is not bound to %s's mesh address %s", p.path, p.mapping, p.site, address)
		}
	}
	if len(published) == 0 {
		t.Fatal("no published port was found, so this test verified nothing")
	}
}

// No two stacks on one site publish the same address and port. Every app
// publishes on its site's mesh address, so two kinds sharing a port cannot
// both start on one site, and the second fails only when its container does.
// The fixture puts every kind beside every clustered one, so a kind given a
// port another already uses fails here.
func TestPublishedPortsAreDistinctPerSite(t *testing.T) {
	seen := map[string]string{}
	for _, p := range publishedPorts(build(t)) {
		host := p.mapping[:strings.LastIndex(p.mapping, ":")]
		key := p.site + " " + host
		if other, ok := seen[key]; ok {
			t.Errorf("%s and %s both publish %s", other, p.path, host)
		}
		seen[key] = p.path
	}
}

// publishedPort is one ports: entry of a rendered compose file.
type publishedPort struct{ path, site, mapping string }

// publishedPorts reads every ports: entry from the plan's compose files.
func publishedPorts(plan *render.Plan) []publishedPort {
	var out []publishedPort
	for _, f := range plan.Files {
		if !strings.HasSuffix(f.Path, "compose.yaml") {
			continue
		}
		site := strings.SplitN(f.Path, "/", 2)[0]
		inPorts := false
		for _, line := range strings.Split(f.Content, "\n") {
			trimmed := strings.TrimSpace(line)
			if trimmed == "ports:" {
				inPorts = true
				continue
			}
			if strings.HasPrefix(trimmed, "#") {
				continue
			}
			if !strings.HasPrefix(trimmed, "- ") {
				inPorts = false
				continue
			}
			if !inPorts {
				continue
			}
			out = append(out, publishedPort{f.Path, site, strings.Trim(strings.TrimPrefix(trimmed, "- "), `"`)})
		}
	}
	return out
}

// A declared image reaches the compose file, and a service nobody declared
// takes the default its kind ships. Both halves matter: the first is what makes
